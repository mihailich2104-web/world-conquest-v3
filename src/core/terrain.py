"""Местность регионов: приблизительная классификация по координатам (без внешних данных высот).

Это игровая абстракция: она влияет на скорость движения, оборону и снабжение армий. Рамки ниже —
грубые контуры известных горных систем, пустынь и джунглей; остальное определяется широтой.
"""
from __future__ import annotations

# вид: (скорость движения, бонус обороны, штраф снабжения в пунктах/день, название)
TERRAIN: dict[str, tuple[float, float, float, str]] = {
    "plains": (1.00, 1.00, 0.0, "Равнины"),
    "forest": (0.80, 1.15, 0.5, "Леса"),
    "mountains": (0.55, 1.45, 1.5, "Горы"),
    "desert": (0.75, 1.00, 2.5, "Пустыня"),
    "jungle": (0.60, 1.25, 2.0, "Джунгли"),
    "arctic": (0.60, 1.10, 2.5, "Арктика"),
}

_MOUNTAINS = [(5, 43, 16, 48), (-8, 41, 3, 43.5), (20, 44, 28, 50), (39, 40, 49, 44.5), (56, 50, 62, 68),
              (60, 36, 100, 42), (68, 27, 98, 36), (88, 26, 105, 34), (-125, 32, -105, 60), (-80, -55, -66, 10),
              (36, 3, 42, 14), (-8, 29, 10, 36), (95, 20, 105, 28), (125, 42, 140, 55), (135, 34, 140, 38)]
_DESERTS = [(-17, 15, 35, 32), (35, 14, 60, 32), (90, 38, 120, 46), (113, -30, 142, -20), (-117, 23, -105, 36),
            (-72, -30, -68, -18), (55, 38, 70, 46), (12, -28, 25, -18), (44, 28, 56, 36)]
_JUNGLES = [(-76, -12, -48, 5), (9, -6, 30, 5), (95, -8, 125, 8), (-92, 8, -77, 18), (140, -10, 152, -2),
            (98, 8, 110, 22), (72, 8, 80, 14), (-60, -5, -50, 6)]


def _in(boxes: list[tuple[float, float, float, float]], lon: float, lat: float) -> bool:
    return any(a <= lon <= c and b <= lat <= d for a, b, c, d in boxes)


def classify(lon: float, lat: float) -> str:
    """Тип местности для точки (lon, lat)."""
    if abs(lat) > 62 or lat < -58:
        return "arctic"
    if _in(_MOUNTAINS, lon, lat):
        return "mountains"
    if _in(_DESERTS, lon, lat):
        return "desert"
    if _in(_JUNGLES, lon, lat):
        return "jungle"
    if 48 <= abs(lat) <= 62 or (abs(lat) > 40 and 100 <= lon <= 140):
        return "forest"
    return "plains"
